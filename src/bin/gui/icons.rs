pub fn icon<'a>(i: Icon, size: f32, color: Color) -> Svg<'a> {
    let doc = format!(r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="{}" fill="white"/></svg>"#, path(i));
    svg(svg::Handle::from_memory(doc.into_bytes()))
        .width(size)
        .height(size)
        .style(move |_, _| svg::Style { color: Some(color) })
}

fn svg<'a>(handle: svg::Handle) -> Svg<'a> {
    Svg::new(handle)
}
